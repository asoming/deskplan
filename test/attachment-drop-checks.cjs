'use strict';
const fs = require('node:fs'), path = require('node:path'), os = require('node:os'), assert = require('node:assert/strict');
const { execFile } = require('node:child_process'), { promisify } = require('node:util');
module.exports = async function attachmentDropChecks(runtime, js, call) {
  if (process.platform !== 'linux') return;
  const fixture = fs.mkdtempSync(path.join(os.tmpdir(), 'rixu-editor-drop-'));
  const file = path.join(fixture, '关联 文件.txt'), folder = path.join(fixture, '项目 workspace');
  fs.writeFileSync(file, 'Keep original contents'); fs.mkdirSync(folder);
  const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
  const until = async (fn, message) => { for (let i = 0; i < 80; i++) { if (await fn()) return; await sleep(50); } throw Error(message); };
  const count = () => js('document.querySelectorAll("#attachments .attachment").length');
  const drop = async (...paths) => {
    await js('document.querySelector("#attachment-drop").scrollIntoView({block:"center"})');
    await sleep(80);
    const point = await js('(()=>{const r=document.querySelector(".attachment-drop-hint").getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()');
    const bounds = runtime.window.getBounds();
    await promisify(execFile)('python3', [path.join(__dirname, 'x11-drop.py'), String(runtime.window.getNativeWindowHandle().readUInt32LE(0)), String(Math.round(bounds.x + point.x)), String(Math.round(bounds.y + point.y)), ...paths]);
  };
  const baseline = runtime.store.state.tasks.length;
  try {
    await js('document.querySelector("#new-task").click()');
    await until(() => js('document.querySelector("#task-dialog").open'), 'new editor open');
    await js('document.querySelector("#task-title").value="附件拖放回归"');
    await js('(()=>{const data=new DataTransfer();data.items.add(new File(["virtual"],"virtual.txt"));document.querySelector("#attachment-drop").dispatchEvent(new DragEvent("drop",{bubbles:true,cancelable:true,dataTransfer:data}));})()');
    await until(() => js('!document.querySelector("#editor-error").hidden'), 'invalid local file shows inline error');
    assert.equal(await count(), 0);
    assert.equal(await js('document.querySelector("#save-task").disabled'), false, 'drop failure releases save button');
    await drop(file, folder);
    await until(async () => await count() === 2, 'draft accepts native file and folder together');
    assert.equal(runtime.store.state.tasks.length, baseline, 'draft attachments do not create background tasks');
    await drop(file, folder); assert.equal(await count(), 2, 'duplicate draft paths are ignored');
    await js('document.querySelector("#task-form").requestSubmit()');
    await until(() => js('!document.querySelector("#task-dialog").open'), 'save draft');
    const task = runtime.store.state.tasks.find(t => t.title === '附件拖放回归');
    assert.deepEqual(task.files.map(f => f.kind).sort(), ['directory', 'file']);
    await js(`document.querySelector('[data-edit="${task.id}"]').click()`);
    await until(() => js('document.querySelector("#task-dialog").open'), 'existing editor open');
    const extra = path.join(fixture, '新增.txt'); fs.writeFileSync(extra, 'Additional attachment');
    await drop(extra, folder);
    await until(async () => await count() === 3, 'existing editor renders added attachment');
    assert.equal(runtime.store.state.tasks.length, baseline + 1, 'drop links to current task only');
    if (process.env.RIXU_ARTIFACTS_DIR) fs.writeFileSync(path.join(process.env.RIXU_ARTIFACTS_DIR, 'attachment-drop.png'), (await runtime.window.webContents.capturePage()).toPNG());
    assert.equal(runtime.store.state.tasks.find(t => t.id === task.id).files.length, 3);
    await js('document.querySelector("#attachments [data-file-remove]").click()');
    await until(async () => await count() === 2, 'attachment remove still works');
    await js('document.querySelector("#task-dialog").close()');
    await js(`document.querySelector('[data-edit="${task.id}"]').click()`);
    await until(async () => await count() === 2, 'attachments retained when reopening');
    const disk = JSON.parse(fs.readFileSync(path.join(process.env.RIXU_DATA_DIR, 'tasks.json')));
    assert.equal(disk.tasks.find(t => t.id === task.id).files.length, 2, 'links saved to disk');
    await call('settings', { language: 'en' });
    assert.equal(await js('document.querySelector(".attachment-drop-hint").textContent'), 'Drop files or folders here, or use Add');
    await js('document.querySelector("#task-dialog").close()');
    await js('document.querySelector("#new-task").click()');
    await until(() => js('document.querySelector("#task-dialog").open'), 'discard editor open');
    await drop(file);
    await until(async () => await count() === 1, 'draft attachment added');
    // Closing a draft must offer the existing unsaved-change choices.
    await js('document.querySelector("#editor-close").click()');
    await until(() => js('document.querySelector("#confirm-dialog").open'), 'draft prompts before discard');
    await js('[...document.querySelectorAll("#confirm-dialog button")].find(b=>b.textContent.includes("Discard")).click()');
    await until(() => js('!document.querySelector("#task-dialog").open'), 'discarded draft closed');
    assert.equal(runtime.store.state.tasks.length, baseline + 1);
    assert.equal(fs.readFileSync(file, 'utf8'), 'Keep original contents'); assert.ok(fs.statSync(folder).isDirectory());
    await call('status', { id: task.id, action: 'delete' });
    runtime.store.purge(task.id);
    await call('settings', { language: 'zh-CN' });
    console.log('Native attachment drops passed: mixed file/folder, draft/save, existing task, duplicate, remove, persistence, discard and bilingual hint');
  } finally { fs.rmSync(fixture, { recursive: true, force: true }); }
};
