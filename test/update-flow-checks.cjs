'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const {Readable}=require('node:stream'),{createHash}=require('node:crypto');
const {assetName}=require('../src/update-download.cjs');
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
const payload=Buffer.alloc(20000,42),hash=createHash('sha256').update(payload).digest('hex');
let installed=0,failInstall=false;
exports.options={updateTarget:{kind:'local'},updateRequest:async(url,signal)=>({size:url.endsWith('.txt')?0:payload.length,body:url.endsWith('.txt')?Readable.from([Buffer.from(`${hash}  ${assetName('9.8.7','local','x64')}\n`)]):Readable.from((async function*(){for(let i=0;i<payload.length;i+=2000){await sleep(30);if(signal.aborted)throw Error('下载已取消');yield payload.subarray(i,i+2000);}})())}),updateInstall:async()=>{if(failInstall)throw Error('test installer refused');installed++;}};
exports.check=async(runtime,js,call,setResponse)=>{
 const until=async(fn)=>{for(let i=0;i<100;i++){if(await fn())return;await sleep(30);}throw Error('update state timed out');};
 setResponse({tag_name:'v9.8.7',draft:false,prerelease:false});await call('updates:check');
 await call('settings',{language:'en'});
 await js('document.querySelector("#settings-button").click()');
 await js('document.querySelector("#settings-download-update").click()');
 await until(()=>runtime.downloader.state.transferred>0);
 assert.match(await js('document.querySelector("[data-update-transfer]").textContent'),/Downloading/);
 await js('document.querySelector("[data-update-cancel]").click()');await until(()=>runtime.downloader.state.status==='error');
 assert.equal(runtime.downloader.state.error,'下载已取消');assert.equal(installed,0);
 await js('document.querySelector("#settings-download-update").click()');await until(()=>runtime.downloader.state.status==='ready');
 assert.match(await js('document.querySelector("[data-update-transfer]").textContent'),/Install and restart/);
 await js('document.querySelector("#update-status").scrollIntoView({block:"end"})');
 if(process.env.RIXU_ARTIFACTS_DIR)fs.writeFileSync(require('node:path').join(process.env.RIXU_ARTIFACTS_DIR,'update-ready.png'),(await runtime.window.webContents.capturePage()).toPNG());
 await js('document.querySelector("#settings-dialog").close()');await sleep(50);assert.equal(installed,0,'download does not install automatically');
 const before=JSON.stringify(runtime.store.state.tasks);failInstall=true;
 await call('updates:install');assert.equal(runtime.downloader.state.status,'ready');assert.equal(installed,0);assert.ok(!runtime.window.isDestroyed());
 failInstall=false;await call('updates:install');assert.equal(installed,1);assert.equal(JSON.stringify(runtime.store.state.tasks),before);
 assert.ok(fs.readdirSync(runtime.store.backupDirectory).some(n=>n.startsWith('before-update-')));
 assert.deepEqual(await js('window.RixuI18n.missing()'),[]);
 await call('settings',{language:'zh-CN'});
};
